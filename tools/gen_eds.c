/*
 * gen_eds.c - 펌웨어의 오브젝트 딕셔너리 테이블(src/co_od.c)에서 EDS 파일을 만든다.
 * EDS 는 CANopen 마스터(ros2_canopen/Lely, python-canopen, CANopen 툴)가 장치를 이해하는 설명서다.
 *
 *   gcc -std=c99 -Isrc tools/gen_eds.c src/co_od.c -o gen_eds && ./gen_eds eds/pico_ak40.eds
 *
 * 테이블이 바뀌면 다시 생성할 것 (펌웨어와 EDS 가 항상 일치하도록).
 */
#include <stdio.h>
#include <string.h>

#include "co_od.h"
#include "config.h"

static const char *access_type(uint8_t f) {
    if (f & OD_CONST) return "const";
    if ((f & OD_R) && (f & OD_W)) return (f & OD_RPDO) ? "rww" : (f & OD_TPDO) ? "rwr" : "rw";
    if (f & OD_W) return "wo";
    return "ro";
}

static void default_value(FILE *o, const od_sub_t *s) {
    switch (s->type) {
    case CO_VSTR:
        fprintf(o, "DefaultValue=%s\n", s->str ? s->str : "");
        return;
    case CO_R32: {
        float f;
        memcpy(&f, &s->def, sizeof(f));
        fprintf(o, "DefaultValue=%g\n", (double)f);
        return;
    }
    case CO_I8:
    case CO_I16:
    case CO_I32:
        fprintf(o, "DefaultValue=%ld\n", (long)od_to_signed(s->def, s->type));
        return;
    default:
        if (s->flags & OD_NODEID) {
            fprintf(o, "DefaultValue=$NODEID+0x%X\n", (unsigned)s->def);
        } else {
            fprintf(o, "DefaultValue=0x%X\n", (unsigned)s->def);
        }
        return;
    }
}

static void entry(FILE *o, const char *section, const od_sub_t *s) {
    fprintf(o, "[%s]\nParameterName=%s\nObjectType=0x7\nDataType=0x%04X\nAccessType=%s\n", section, s->name,
            s->type, access_type(s->flags));
    default_value(o, s);
    fprintf(o, "PDOMapping=%d\n\n", (s->flags & (OD_TPDO | OD_RPDO)) ? 1 : 0);
}

static void object_list(FILE *o, const char *title, int which) {
    int count = 0;
    for (size_t i = 0; i < co_od_table_len; i++) {
        uint16_t idx = co_od_table[i].index;
        bool mandatory = idx == 0x1000 || idx == 0x1001 || idx == 0x1018;
        bool manuf = idx >= 0x2000 && idx < 0x6000;
        int kind = mandatory ? 0 : manuf ? 2 : 1;
        if (kind == which) count++;
    }
    fprintf(o, "[%s]\nSupportedObjects=%d\n", title, count);
    int k = 0;
    for (size_t i = 0; i < co_od_table_len; i++) {
        uint16_t idx = co_od_table[i].index;
        bool mandatory = idx == 0x1000 || idx == 0x1001 || idx == 0x1018;
        bool manuf = idx >= 0x2000 && idx < 0x6000;
        int kind = mandatory ? 0 : manuf ? 2 : 1;
        if (kind == which) fprintf(o, "%d=0x%04X\n", ++k, idx);
    }
    fprintf(o, "\n");
}

int main(int argc, char **argv) {
    const char *path = argc > 1 ? argv[1] : "pico_ak40.eds";
    FILE *o = fopen(path, "w");
    if (!o) {
        perror(path);
        return 1;
    }

    fprintf(o,
            /* EDS 파서가 UTF-8 을 가정하지 않을 수 있어 ASCII 만 사용 */
            "; Generated by tools/gen_eds.c from src/co_od.c - do not edit by hand.\n"
            "; Units: position 0.0001 rad, velocity 0.001 rad/s, acceleration 0.001 rad/s^2,\n"
            ";        torque/current per mille of rated value (0x6076 / 0x6075)\n\n"
            "[FileInfo]\nFileName=pico_ak40.eds\nFileVersion=1\nFileRevision=0\nEDSVersion=4.0\n"
            "Description=%s CiA 402 gateway (one node per AK40-10 axis)\n"
            "CreationTime=12:00PM\nCreationDate=11-16-2026\nCreatedBy=pico_zero-canopen\n"
            "ModificationTime=12:00PM\nModificationDate=11-16-2026\nModifiedBy=pico_zero-canopen\n\n",
            CO_DEVICE_NAME);
    fprintf(o,
            "[DeviceInfo]\nVendorName=pico_zero-canopen\nVendorNumber=0x%08X\nProductName=%s\n"
            "ProductNumber=0x%08X\nRevisionNumber=0x%08X\nOrderCode=\n"
            "BaudRate_10=0\nBaudRate_20=0\nBaudRate_50=0\nBaudRate_125=1\nBaudRate_250=1\nBaudRate_500=1\n"
            "BaudRate_800=1\nBaudRate_1000=1\nSimpleBootUpMaster=0\nSimpleBootUpSlave=1\nGranularity=8\n"
            "DynamicChannelsSupported=0\nCompactPDO=0\nGroupMessaging=0\nNrOfRXPDO=%d\nNrOfTXPDO=%d\n"
            "LSS_Supported=0\n\n",
            (unsigned)CO_VENDOR_ID, CO_DEVICE_NAME, (unsigned)CO_PRODUCT_CODE, (unsigned)CO_REVISION, CO_PDO_COUNT,
            CO_PDO_COUNT);
    fprintf(o, "[DummyUsage]\n");
    for (int i = 1; i <= 7; i++) fprintf(o, "Dummy%04X=0\n", i);
    fprintf(o, "\n[Comments]\nLines=0\n\n");

    object_list(o, "MandatoryObjects", 0);
    object_list(o, "OptionalObjects", 1);
    object_list(o, "ManufacturerObjects", 2);

    for (size_t i = 0; i < co_od_table_len; i++) {
        const od_obj_t *obj = &co_od_table[i];
        char sec[16];
        if (obj->code == OD_VAR) {
            snprintf(sec, sizeof(sec), "%04X", obj->index);
            entry(o, sec, &obj->subs[0]);
            continue;
        }
        fprintf(o, "[%04X]\nParameterName=%s\nObjectType=0x%X\nSubNumber=%u\n\n", obj->index, obj->name, obj->code,
                obj->nsub);
        for (uint8_t k = 0; k < obj->nsub; k++) {
            snprintf(sec, sizeof(sec), "%04Xsub%X", obj->index, obj->subs[k].sub);
            entry(o, sec, &obj->subs[k]);
        }
    }
    fclose(o);
    printf("wrote %s (%u objects)\n", path, (unsigned)co_od_table_len);
    return 0;
}
